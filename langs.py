def t(key, lang="uz", **kwargs):
    d = LANGS.get(lang, LANGS["uz"])
    text = d.get(key, LANGS["uz"].get(key, key))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text


def lang_keyboard():
    rows = []
    for code in ("uz", "ru", "en"):
        d = LANGS[code]
        rows.append([{"text": d["flag"] + " " + d["name"], "callback_data": "lang_" + code}])
    return {"inline_keyboard": rows}


def get_user_lang(user_id):
    import storage
    user = storage.data.get("users", {}).get(str(user_id))
    if user:
        return user.get("lang", "uz")
    return "uz"


def set_user_lang(user_id, lang):
    import storage
    user = storage.data.get("users", {}).get(str(user_id))
    if user:
        user["lang"] = lang
        storage.save_data()
